import { useCallback } from 'react';
import type { Briefing } from '../types';

interface Props {
    briefing: Briefing | null;
}

export function BriefingTab({ briefing }: Props) {
    const exportBriefing = useCallback(() => {
        if (!briefing) return;

        const lines: string[] = [
            '═══════════════════════════════════════════════════',
            '   SILENTSCRIBE 360 — EXECUTIVE BRIEFING',
            '   Zero-Trust • On-Device • Confidential',
            '═══════════════════════════════════════════════════',
            '',
            `Generated: ${new Date(briefing.metadata.generatedAt).toLocaleString()}`,
            `Duration: ${briefing.metadata.durationSeconds}s | Words: ${briefing.metadata.wordCount}`,
            `Visual Context: ${briefing.metadata.hasVisualContext ? 'Yes' : 'No'}`,
            `Model: ${briefing.metadata.modelUsed} | Tokens: ${briefing.metadata.tokensUsed}`,
            '',
            '───────────────────────────────────────────────────',
            '  EXECUTIVE SUMMARY',
            '───────────────────────────────────────────────────',
            '',
            briefing.executiveSummary,
            '',
        ];

        if (briefing.keyPoints.length > 0) {
            lines.push('───────────────────────────────────────────────────');
            lines.push('  KEY POINTS');
            lines.push('───────────────────────────────────────────────────');
            lines.push('');
            briefing.keyPoints.forEach((point, i) => {
                lines.push(`  ${i + 1}. ${point}`);
            });
            lines.push('');
        }

        if (briefing.decisions.length > 0) {
            lines.push('───────────────────────────────────────────────────');
            lines.push('  DECISIONS');
            lines.push('───────────────────────────────────────────────────');
            lines.push('');
            briefing.decisions.forEach((d, i) => {
                lines.push(`  ${i + 1}. ${d}`);
            });
            lines.push('');
        }

        if (briefing.actionItems.length > 0) {
            lines.push('───────────────────────────────────────────────────');
            lines.push('  ACTION ITEMS');
            lines.push('───────────────────────────────────────────────────');
            lines.push('');
            briefing.actionItems.forEach((a, i) => {
                lines.push(`  ${i + 1}. ${a.task}`);
                lines.push(`     Owner: ${a.owner} | Deadline: ${a.deadline}`);
            });
            lines.push('');
        }

        if (briefing.openQuestions.length > 0) {
            lines.push('───────────────────────────────────────────────────');
            lines.push('  OPEN QUESTIONS');
            lines.push('───────────────────────────────────────────────────');
            lines.push('');
            briefing.openQuestions.forEach((q, i) => {
                lines.push(`  ${i + 1}. ${q}`);
            });
            lines.push('');
        }

        lines.push('═══════════════════════════════════════════════════');
        lines.push('  Generated by SilentScribe 360 — 100% On-Device');
        lines.push('═══════════════════════════════════════════════════');

        const blob = new Blob([lines.join('\n')], { type: 'text/plain' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `briefing-${new Date().toISOString().slice(0, 10)}.txt`;
        a.click();
        URL.revokeObjectURL(url);
    }, [briefing]);

    const copyToClipboard = useCallback(async () => {
        if (!briefing) return;

        const text = [
            `# Executive Briefing`,
            ``,
            `## Summary`,
            briefing.executiveSummary,
            ``,
            `## Key Points`,
            ...briefing.keyPoints.map(p => `- ${p}`),
            ``,
            `## Decisions`,
            ...briefing.decisions.map(d => `- ${d}`),
            ``,
            `## Action Items`,
            ...briefing.actionItems.map(a => `- **${a.task}** — Owner: ${a.owner}, Deadline: ${a.deadline}`),
            ``,
            `## Open Questions`,
            ...briefing.openQuestions.map(q => `- ${q}`),
        ].join('\n');

        try {
            await navigator.clipboard.writeText(text);
        } catch {
            // Fallback
            const ta = document.createElement('textarea');
            ta.value = text;
            document.body.appendChild(ta);
            ta.select();
            document.execCommand('copy');
            document.body.removeChild(ta);
        }
    }, [briefing]);

    if (!briefing) {
        return (
            <div className="tab-panel">
                <div className="empty-state">
                    <span className="empty-state-icon">📋</span>
                    <h3>No Briefing Yet</h3>
                    <p>
                        Record a conversation in the Capture tab, then generate an executive briefing.
                        All processing happens on your device.
                    </p>
                </div>
            </div>
        );
    }

    return (
        <div className="tab-panel">
            <div className="briefing-view">
                {/* Header */}
                <div className="briefing-header">
                    <h2>Executive Briefing</h2>
                    <p>Generated on-device • No data left this browser</p>
                    <div className="briefing-meta">
                        <span className="briefing-meta-item">
                            🕐 {briefing.metadata.durationSeconds}s captured
                        </span>
                        <span className="briefing-meta-item">
                            📝 {briefing.metadata.wordCount} words
                        </span>
                        {briefing.metadata.hasVisualContext && (
                            <span className="briefing-meta-item">
                                📸 Visual context included
                            </span>
                        )}
                        <span className="briefing-meta-item">
                            ⚡ {(briefing.metadata.processingTimeMs / 1000).toFixed(1)}s processing
                        </span>
                    </div>
                </div>

                {/* Executive Summary */}
                <div className="briefing-card">
                    <div className="briefing-card-header">
                        <div className="briefing-card-icon summary">📊</div>
                        <span className="briefing-card-title">Executive Summary</span>
                    </div>
                    <div className="briefing-card-body">
                        <p>{briefing.executiveSummary}</p>
                    </div>
                </div>

                {/* Key Points */}
                {briefing.keyPoints.length > 0 && (
                    <div className="briefing-card">
                        <div className="briefing-card-header">
                            <div className="briefing-card-icon keypoints">💡</div>
                            <span className="briefing-card-title">Key Points</span>
                        </div>
                        <ul className="briefing-list">
                            {briefing.keyPoints.map((point, i) => (
                                <li key={i}>
                                    <span className="list-bullet" />
                                    <span>{point}</span>
                                </li>
                            ))}
                        </ul>
                    </div>
                )}

                {/* Decisions */}
                {briefing.decisions.length > 0 && (
                    <div className="briefing-card">
                        <div className="briefing-card-header">
                            <div className="briefing-card-icon decisions">⚖️</div>
                            <span className="briefing-card-title">Decisions Made</span>
                        </div>
                        <ul className="briefing-list decisions">
                            {briefing.decisions.map((decision, i) => (
                                <li key={i}>
                                    <span className="list-bullet" />
                                    <span>{decision}</span>
                                </li>
                            ))}
                        </ul>
                    </div>
                )}

                {/* Action Items */}
                {briefing.actionItems.length > 0 && (
                    <div className="briefing-card">
                        <div className="briefing-card-header">
                            <div className="briefing-card-icon actions">✅</div>
                            <span className="briefing-card-title">Action Items</span>
                        </div>
                        <ul className="briefing-list actions">
                            {briefing.actionItems.map((item, i) => (
                                <li key={i}>
                                    <span className="list-bullet" />
                                    <div>
                                        <span>{item.task}</span>
                                        <div className="action-item-details">
                                            <span>👤 {item.owner}</span>
                                            <span>📅 {item.deadline}</span>
                                        </div>
                                    </div>
                                </li>
                            ))}
                        </ul>
                    </div>
                )}

                {/* Open Questions */}
                {briefing.openQuestions.length > 0 && (
                    <div className="briefing-card">
                        <div className="briefing-card-header">
                            <div className="briefing-card-icon questions">❓</div>
                            <span className="briefing-card-title">Open Questions</span>
                        </div>
                        <ul className="briefing-list questions">
                            {briefing.openQuestions.map((question, i) => (
                                <li key={i}>
                                    <span className="list-bullet" />
                                    <span>{question}</span>
                                </li>
                            ))}
                        </ul>
                    </div>
                )}

                {/* Export actions */}
                <div className="briefing-actions">
                    <button className="btn" onClick={copyToClipboard}>
                        📋 Copy to Clipboard
                    </button>
                    <button className="btn btn-primary" onClick={exportBriefing}>
                        💾 Export Briefing
                    </button>
                </div>
            </div>
        </div>
    );
}
